import { expect, test } from "@playwright/test";
import { createProject, createTask, openProject, selectAllTasks } from "./helpers";

test("task archive, restore and permanent deletion use the real lifecycle API", async ({ page }) => {
  const project = await createProject(page, "任务生命周期");
  await createTask(page, project.id, "生命周期任务");
  await openProject(page, project.title);
  await selectAllTasks(page);
  const actions = page.getByRole("region", { name: "任务操作", exact: true });
  await actions.getByRole("button", { name: "归档", exact: true }).click();
  const archive = page.getByRole("dialog", { name: "归档任务", exact: true });
  await archive.getByRole("button", { name: "归档任务", exact: true }).click();
  await expect(archive).toBeHidden();
  await expect(page.locator(".task-list-row:not(.is-create)")).toHaveCount(0);
  await page.getByRole("button", { name: "已归档", exact: true }).click();
  const browser = page.getByRole("dialog", { name: "任务归档与回收站" });
  await browser.locator("label").filter({ has: page.getByRole("checkbox", { name: "选择任务 · 生命周期任务" }) }).click();
  await expect(browser.getByRole("checkbox", { name: "选择任务 · 生命周期任务" })).toBeChecked();
  await browser.getByRole("button", { name: "取消归档", exact: true }).click();
  const unarchive = page.getByRole("dialog", { name: "取消归档", exact: true });
  await unarchive.getByRole("button", { name: "取消归档", exact: true }).click();
  await expect(unarchive).toBeHidden();
  await expect(browser.getByText("这里没有任务。")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(browser).toBeHidden();
  await expect(page.locator(".task-list-row:not(.is-create)")).toHaveCount(1);
  await selectAllTasks(page);
  await actions.getByRole("button", { name: "删除", exact: true }).click();
  const trash = page.getByRole("dialog", { name: "删除任务", exact: true });
  await trash.getByRole("button", { name: "删除任务", exact: true }).click();
  await expect(trash).toBeHidden();
  await page.getByRole("button", { name: "已归档", exact: true }).click();
  await browser.getByRole("button", { name: "回收站", exact: true }).click();
  await browser.locator("label").filter({ has: page.getByRole("checkbox", { name: "选择任务 · 生命周期任务" }) }).click();
  await browser.getByRole("button", { name: "恢复", exact: true }).click();
  const restore = page.getByRole("dialog", { name: "恢复任务", exact: true });
  await restore.getByRole("button", { name: "恢复任务", exact: true }).click();
  await expect(restore).toBeHidden();
  await expect(browser.getByText("这里没有任务。")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(browser).toBeHidden();
  await expect(page.locator(".task-list-row:not(.is-create)")).toHaveCount(1);
  await selectAllTasks(page);
  await actions.getByRole("button", { name: "删除", exact: true }).click();
  await trash.getByRole("button", { name: "删除任务", exact: true }).click();
  await expect(trash).toBeHidden();
  await page.getByRole("button", { name: "项目配置", exact: true }).click();
  await page.getByRole("button", { name: "任务回收站", exact: true }).click();
  await expect(browser).toBeVisible();
  await browser.locator("label").filter({ has: page.getByRole("checkbox", { name: "选择任务 · 生命周期任务" }) }).click();
  await expect(browser.getByRole("checkbox", { name: "选择任务 · 生命周期任务" })).toBeChecked();
  await browser.getByRole("button", { name: "永久删除", exact: true }).click();
  const purge = page.getByRole("dialog", { name: "永久删除任务", exact: true });
  await expect(purge.getByRole("checkbox", { name: "归档全部生成结果后删除" })).toBeChecked();
  await purge.getByRole("button", { name: "永久删除任务", exact: true }).click();
  await expect(purge).toBeHidden();
  await expect(browser.getByText("这里没有任务。")).toBeVisible();
  const response = await page.request.get(`/api/v1/projects/${project.id}/workspace?scope=trash`);
  expect(response.ok()).toBeTruthy();
  expect((await response.json()).tasks).toEqual([]);
});
